package PROBLEM_PRACTICE_IN_JAVA;

public class seventeen_problem {
    public static void main(String[] args) {

        for (int i = 1; i <= 10; i++) {
            for (int j = 1; j <= 10; j++) {

                System.out.print(i * j + "\t");
            }
            System.out.println();
        }
    }
}
